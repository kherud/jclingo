package org.potassco.clingo.internal;

import java.lang.foreign.Arena;
import java.lang.foreign.FunctionDescriptor;
import java.lang.foreign.Linker;
import java.lang.foreign.MemorySegment;
import java.lang.invoke.MethodHandle;
import java.lang.invoke.MethodHandles;
import java.lang.invoke.MethodType;

/**
 * Creates the function pointers clingo calls back into.
 * <p>
 * An exception escaping an upcall terminates the JVM, so every stub has to catch everything. That guard is not
 * written by hand per callback but composed into the method handle a stub is built from, which is why this class is
 * the only place allowed to call {@link Linker#upcallStub}. The original {@link Throwable} is kept - never flattened
 * into a message - so that {@link Clingo#check} can rethrow it unchanged.
 */
public final class Upcalls {

    /**
     * Error of a callback that ran synchronously inside our own downcall, hence on this very thread.
     */
    private static final ThreadLocal<Throwable> PENDING = new ThreadLocal<>();

    private Upcalls() {
    }

    /**
     * Creates a guarded upcall stub for the callback {@code implementation}.
     *
     * @param type           the functional interface of the callback, as generated by jextract
     * @param implementation the callback body, which may throw freely
     * @param descriptor     the descriptor of the callback, as generated by jextract
     * @param arena          the arena the stub lives in; it must outlive clingo's use of the callback
     * @param policy         what to do when the body throws
     */
    public static <T> MemorySegment stub(Class<T> type, T implementation, FunctionDescriptor descriptor, Arena arena,
                                         ErrorPolicy policy) {
        MethodHandle target = target(type, implementation, descriptor);
        MethodHandle guarded = MethodHandles.catchException(target, Throwable.class, policy.handlerFor(descriptor));
        return Linker.nativeLinker().upcallStub(guarded, descriptor, arena);
    }

    /**
     * Remembers an error of a callback running on the calling thread, to be rethrown by {@link Clingo#check}.
     */
    static void setPending(Throwable error) {
        if (PENDING.get() == null) {
            PENDING.set(error);
        }
    }

    /**
     * @return the error of a callback that ran on this thread since the last call, if any
     */
    static Throwable takePending() {
        Throwable pending = PENDING.get();
        if (pending != null) {
            PENDING.remove();
        }
        return pending;
    }

    private static <T> MethodHandle target(Class<T> type, T implementation, FunctionDescriptor descriptor) {
        MethodType signature = descriptor.toMethodType();
        try {
            return MethodHandles.publicLookup().findVirtual(type, "apply", signature).bindTo(implementation);
        }
        catch (ReflectiveOperationException e) {
            throw new AssertionError("no callback method " + signature + " on " + type, e);
        }
    }
}
